export interface CountryPack {
  code: CountryCode;
  label: string;
  /** Local name of the periodic technical inspection. */
  inspection: { key: string; label: { en: string; de: string; ro: string }; months: number };
  docTypes: DocTypeDef[];
  cmr: {
    /** Heading printed on the consignment note. */
    title: string;
    subtitle: string;
    /** Legal reference line printed in the footer. */
    footer: string;
  };
  distanceUnit: "km" | "mi";
  weightUnit: "kg" | "lb";
}

function pack(
  code: CountryCode,
  label: string,
  inspection: CountryPack["inspection"],
  cmr: CountryPack["cmr"],
): CountryPack {
  return {
    code,
    label,
    inspection,
    docTypes: [
      { ...inspection, owner: "vehicle" },
      ...COMMON_VEHICLE,
      ...COMMON_DRIVER,
      ...COMMON_CARRIER,
    ],
    cmr,
    distanceUnit: "km",
    weightUnit: "kg",
  };
}

