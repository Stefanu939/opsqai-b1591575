export function countryPack(code: string | null | undefined): CountryPack {
  const key = (code ?? "generic").toLowerCase() as CountryCode;
  return COUNTRY_PACKS[key] ?? COUNTRY_PACKS.generic;
}

export function docTypeLabel(
  code: string | null | undefined,
  docType: string,
  lang: "en" | "de" | "ro",
): string {
  const found = countryPack(code).docTypes.find((d) => d.key === docType);
  return found ? found.label[lang] : docType;
}

