export function translateLabel(s: string, lang: string): string {
  const row = L[s];
  if (!row) return s;
  return lang === "ro" ? row[0] : lang === "de" ? row[1] : s;
}

export function useUiLabel() {
  const { lang } = useT();
  return <T,>(v: T): T => (typeof v === "string" ? (translateLabel(v, lang) as T) : v);
}
